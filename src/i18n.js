const DICTS = { ar, fr, en };
const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";

export function makeI18n(lang) {
  const dict = DICTS[lang] || ar;
  const n = (x) => (lang === "ar" ? String(x).replace(/\d/g, (d) => AR_DIGITS[d]).replace(".", "٫") : String(x));
  const t = (key, vars = {}) =>
    (dict[key] ?? ar[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (typeof vars[k] === "number" ? n(vars[k]) : vars[k] ?? ""));
  const pages = (count) => {
    if (lang === "ar") {
      if (count === 1) return "صفحة واحدة";
      if (count === 2) return "صفحتان";
      const mod = count % 100;
      return `${n(count)} ${mod >= 3 && mod <= 10 ? "صفحات" : "صفحة"}`;
    }
    if (lang === "fr") return `${count} ${count > 1 ? "pages" : "page"}`;
    return `${count} ${count === 1 ? "page" : "pages"}`;
  };
  const days = (count) => {
    if (lang === "ar") {
      if (count === 1) return "يوم";
      if (count === 2) return "يومين";
      const mod = count % 100;
      return `${n(count)} ${mod >= 3 && mod <= 10 ? "أيام" : "يومًا"}`;
    }
    if (lang === "fr") return `${count} ${count > 1 ? "jours" : "jour"}`;
    return `${count} ${count === 1 ? "day" : "days"}`;
  };
  const dir = lang === "ar" ? "rtl" : "ltr";
  // الأسهم تتبع اتجاه الواجهة: "رجوع" في العربية سهم لليمين
  const arrows = dir === "rtl" ? { back: "→", forward: "←" } : { back: "←", forward: "→" };
  const locale = { ar: "ar-SA", fr: "fr-FR", en: "en-GB" }[lang] + "-u-ca-islamic-umalqura";
  return { lang, t, n, pages, days, dir, arrows, locale };
}

export function useI18n() {
  return makeI18n(useStore().settings.lang);
}

export function i18nNow() {
  return makeI18n(getState().settings.lang);
}
